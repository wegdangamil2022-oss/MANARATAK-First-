export function dashboardLabel(key: string, language: string): string {
  return dashboardText[key]?.[language === 'ar' ? 0 : 1] ?? key;
}
export function dashboardTime(value: string | null, language: string): string {
  return value
    ? new Intl.DateTimeFormat(language === 'ar' ? 'ar' : 'en-US', {
        dateStyle: 'medium',
        timeStyle: 'short',
        timeZone: 'UTC',
      }).format(new Date(value)) + ' UTC'
    : dashboardLabel('unknown', language);
}
