import http from 'node:http';
import { execFile } from 'node:child_process';
import { readFile } from 'node:fs/promises';
import { promisify } from 'node:util';

const execFileAsync = promisify(execFile);
const args = new Map(process.argv.slice(2).map((arg, index, all) => [arg, all[index + 1]]));
const durationSeconds = Math.max(1, Number(args.get('--duration') || 300));
const baseUrl = args.get('--url') || 'http://localhost:3000';
const probePath = args.get('--probe');

const parsedBaseUrl = new URL(baseUrl);
if (parsedBaseUrl.protocol !== 'http:' || !['localhost', '127.0.0.1', '::1'].includes(parsedBaseUrl.hostname)) {
  throw new Error('Only localhost targets are allowed; this verifier must not generate external traffic.');
}

const monitoredRequests = [];

async function readNetworkCounters() {
  if (process.platform === 'win32') {
    try {
      const script = "$s=Get-NetAdapterStatistics; [pscustomobject]@{sent=[uint64](($s|Measure-Object SentBytes -Sum).Sum);received=[uint64](($s|Measure-Object ReceivedBytes -Sum).Sum)}|ConvertTo-Json -Compress";
      const { stdout } = await execFileAsync('powershell.exe', ['-NoProfile', '-Command', script]);
      return JSON.parse(stdout.trim());
    } catch {
      return null;
    }
  }
  if (process.platform === 'linux') {
    try {
      const data = await readFile('/proc/net/dev', 'utf8');
      let sent = 0;
      let received = 0;
      for (const line of data.split('\n').slice(2)) {
        const [name, counters] = line.split(':');
        if (!name || !counters || name.trim() === 'lo') continue;
        const values = counters.trim().split(/\s+/).map(Number);
        received += values[0] || 0;
        sent += values[8] || 0;
      }
      return { sent, received };
    } catch {
      return null;
    }
  }
  return null;
}

async function countActiveConnections() {
  try {
    const command = process.platform === 'win32' ? 'powershell.exe' : 'sh';
    const commandArgs = process.platform === 'win32'
      ? ['-NoProfile', '-Command', "(Get-NetTCPConnection -State Established -ErrorAction SilentlyContinue|Measure-Object).Count"]
      : ['-c', "ss -H state established 2>/dev/null | wc -l"];
    const { stdout } = await execFileAsync(command, commandArgs);
    return Number(stdout.trim());
  } catch {
    return null;
  }
}

async function requestProbe(pathname) {
  const target = new URL(pathname, parsedBaseUrl);
  if (target.origin !== parsedBaseUrl.origin) {
    throw new Error('Probe paths must remain on the configured localhost origin.');
  }
  const startedAt = Date.now();
  return new Promise((resolve) => {
    const request = http.get(target, (response) => {
      let receivedBytes = 0;
      response.on('data', (chunk) => { receivedBytes += chunk.length; });
      response.on('end', () => {
        const result = { method: 'GET', target: target.pathname, status: response.statusCode, receivedBytes, durationMs: Date.now() - startedAt };
        monitoredRequests.push(result);
        resolve(result);
      });
    });
    request.on('error', (error) => {
      const result = { method: 'GET', target: target.pathname, error: error.code || 'REQUEST_FAILED' };
      monitoredRequests.push(result);
      resolve(result);
    });
  });
}

const startedAt = new Date();
const beforeCounters = await readNetworkCounters();
const connectionsBefore = await countActiveConnections();
const measurementStartedAt = Date.now();
if (probePath) await requestProbe(probePath);
await new Promise((resolve) => setTimeout(resolve, durationSeconds * 1000));
const afterCounters = await readNetworkCounters();
const measuredDurationSeconds = (Date.now() - measurementStartedAt) / 1000;
const connectionsAfter = await countActiveConnections();

console.log(JSON.stringify({
  startedAt: startedAt.toISOString(),
  finishedAt: new Date().toISOString(),
  requestedDurationSeconds: durationSeconds,
  measuredDurationSeconds,
  targetScope: 'LOCALHOST_ONLY',
  monitoredHttpRequests: monitoredRequests,
  activeConnections: { before: connectionsBefore, after: connectionsAfter },
  bytes: beforeCounters && afterCounters ? {
    sent: afterCounters.sent - beforeCounters.sent,
    received: afterCounters.received - beforeCounters.received,
    scope: 'OS_NETWORK_ADAPTER_AGGREGATE',
  } : 'BYTE MEASUREMENT UNAVAILABLE',
  limitations: [
    'OS adapter bytes include traffic from every process, including Codex and browsers.',
    'Only requests generated by this verifier are counted as monitored HTTP requests.',
    'Run a no-runtime baseline and a MANARATAK run for the same duration before comparing results.',
  ],
}, null, 2));
